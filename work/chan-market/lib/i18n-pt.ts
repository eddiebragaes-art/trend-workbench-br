/** Translate one English UI string to Portuguese, preserving surrounding spaces. */
export function toPt(en: string): string {
  if (!en) return en;
  const lead = en.match(/^\s*/)![0], trail = en.match(/\s*$/)![0];
  const core = en.trim();
  const hit = exact[core];
  if (hit !== undefined) return lead + hit + trail;
  for (const [re, out] of patterns) if (re.test(core)) return lead + core.replace(re, out) + trail;
  return en;
}

export function pickText(language: UiLanguage, zh: string, en: string): string {
  return language === 'zh' ? zh : language === 'pt' ? toPt(en) : en;
}

export function localeFor(language: UiLanguage): string {
  return language === 'zh' ? 'zh-CN' : language === 'pt' ? 'pt-BR' : 'en-US';
}

